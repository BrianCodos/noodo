// Ordered component modules preserve the existing cascade. Edit styles/workspace, not dist/workspace.css.
const fs=require('node:fs'),path=require('node:path');
const base=path.join(__dirname,'../styles/workspace');
const manifest=JSON.parse(fs.readFileSync(path.join(base,'manifest.json'),'utf8'));
const result='/* Generated by scripts/build-workspace.cjs. Edit styles/workspace sources. */\n'+manifest.map(file=>fs.readFileSync(path.join(base,file),'utf8').trimEnd()).join('\n\n')+'\n';
const target=path.join(__dirname,'../dist/workspace.css');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==result){console.error('Workspace CSS is stale. Run node scripts/build-workspace.cjs');process.exit(1);}}else fs.writeFileSync(target,result);
